import fs from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const coreText=fs.readFileSync(new URL('data/core-knowledge.v0.1.jsonld',root),'utf8');
const seedText=fs.readFileSync(new URL('data/seoul-urban-flood.seed.json',root),'utf8');
const core=JSON.parse(coreText), seed=JSON.parse(seedText);
const digest=createHash('sha256').update(coreText+'\n'+seedText).digest('hex');
const content='// Generated by ontology/src/build-research-data.mjs. Do not edit by hand.\n'+
  'export const knowledgeDigest='+JSON.stringify(digest)+';\n'+
  'export const core='+JSON.stringify(core)+';\n'+
  'export const defaultSeed='+JSON.stringify(seed)+';\n';
const target=new URL('src/research-data.mjs',root);
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content)throw Error('연구용 데이터 번들을 다시 생성하세요.');
}else fs.writeFileSync(target,content);
